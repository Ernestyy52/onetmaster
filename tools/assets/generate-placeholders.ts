function buildWarden() {
  const sheet = new Canvas(96 * 4, 112);
  for (let f = 0; f < 4; f++) {
    const c = new Canvas(96, 112);
    const attack = f === 2;
    const hurt = f === 3;
    const dy = f === 1 ? -1 : 0;
    const steel = hurt ? hex('#e7ecff') : hex('#5b7fb8');
    const steelD = hurt ? hex('#c6cff0') : hex('#3c5a8c');
    // legs
    c.rect(30, 84, 12, 22, steelD);
    c.rect(54, 84, 12, 22, steelD);
    c.rect(27, 102, 18, 6, hex('#2d3f63'));
    c.rect(51, 102, 18, 6, hex('#2d3f63'));
    // gear body
    const gx = 48;
    const gy = 56 + dy;
    for (let k = 0; k < 12; k++) {
      const a = (k / 12) * Math.PI * 2 + (f === 1 ? 0.13 : 0);
      c.ellipse(gx + Math.cos(a) * 30, gy + Math.sin(a) * 30, 5, 5, steelD);
    }
    c.ellipse(gx, gy, 30, 30, steel);
    c.ellipse(gx - 6, gy - 8, 16, 14, shade(steel, 0.18));
    c.ellipse(gx, gy, 12, 12, hex('#26324f'));
    c.ellipse(gx, gy, 8, 8, attack ? hex('#ffef9a') : hex('#5ff0ff'));
    c.ellipse(gx - 2, gy - 2, 3, 3, hex('#ffffff'));
    // arms (pistons)
    const armY = attack ? 30 : 50;
    c.rect(8, armY + dy, 12, 30, steelD);
    c.rect(76, armY + dy, 12, 30, steelD);
    c.ellipse(14, armY + 32 + dy, 9, 8, hex('#e8c25a'));
    c.ellipse(82, armY + 32 + dy, 9, 8, hex('#e8c25a'));
    // head bolts
    c.rect(40, 18 + dy, 16, 8, steelD);
    c.rect(44, 12 + dy, 8, 6, hex('#e8c25a'));
    c.outline(OUTLINE);
    const w = new Canvas(96, 112);
    shadow(w, 48, 106, 30, 6);
    w.blit(c, 0, 0);
    sheet.blit(w, f * 96, 0);
  }
  sheet.save(`${OUT}/sprites/warden.png`);
  register({ key: 'warden', file: 'sprites/warden.png', category: 'spritesheet', width: 384, height: 112, frameWidth: 96, frameHeight: 112, frames: 4, anchor: { x: 0.5, y: 0.95 }, notes: 'idle×2, attack, hurt' });
}

