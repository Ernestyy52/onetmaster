// ─────────────────────────── Characters ───────────────────────────
type Dir = 'down' | 'left' | 'right' | 'up';
type Pose = 'idle' | 'walk' | 'attack' | 'hurt' | 'victory';
const DIRS: Dir[] = ['down', 'left', 'right', 'up'];
const FRAMES: { pose: Pose; f: number }[] = [
  { pose: 'idle', f: 0 }, { pose: 'idle', f: 1 },
  { pose: 'walk', f: 0 }, { pose: 'walk', f: 1 }, { pose: 'walk', f: 2 }, { pose: 'walk', f: 3 },
  { pose: 'attack', f: 0 }, { pose: 'attack', f: 1 },
  { pose: 'hurt', f: 0 }, { pose: 'victory', f: 0 },
];

interface Look {
  skin: RGBA; hair: RGBA; tunic: RGBA; tunicDark: RGBA; pants: RGBA; boots: RGBA; accent: RGBA;
  robe: boolean; hat: boolean; weapon: 'sword' | 'staff';
}

function drawCharacter(c: Canvas, ox: number, oy: number, dir: Dir, pose: Pose, f: number, L: Look) {
  const cx = ox + 24;
  const bob = pose === 'idle' ? f : pose === 'walk' ? [0, -1, 0, -1][f] : 0;
  const lean = pose === 'hurt' ? (dir === 'right' ? -2 : 2) : 0;
  const top = oy + 18 + bob;
  const side = dir === 'left' ? -1 : dir === 'right' ? 1 : 0;
  // legs
  const stride = pose === 'walk' ? [0, 2, 0, -2][f] : 0;
  const legY = oy + 49;
  {
    const lx1 = cx - 5 + lean + (side ? stride : 0);
    const lx2 = cx + 1 + lean - (side ? stride : 0);
    const ly1 = legY + (side ? 0 : Math.min(0, -stride));
    const ly2 = legY + (side ? 0 : Math.min(0, stride));
    c.rect(lx1, ly1, 4, 9, L.pants);
    c.rect(lx2, ly2, 4, 9, L.pants);
    c.rect(lx1, ly1 + 7, 4 + (side > 0 ? 1 : 0), 3, L.boots);
    c.rect(lx2 - (side < 0 ? 1 : 0), ly2 + 7, 4 + (side < 0 ? 1 : 0), 3, L.boots);
  }
  // torso
  const tx = cx - 7 + lean;
  const ty = top + 18;
  c.rect(tx, ty, 14, 13, L.tunic);
  c.rect(tx, ty, 3, 13, shade(L.tunic, 0.15));
  c.rect(tx + 11, ty, 3, 13, L.tunicDark);
  if (L.robe) {
    c.rect(tx - 1, ty + 9, 16, 9, L.tunic);
    c.rect(tx + 11, ty + 9, 4, 9, L.tunicDark);
  }
  c.rect(tx, ty + 8, 14, 2, L.accent); // belt / sash
  // arms + weapon
  const armColor = L.tunicDark;
  const attackReach = pose === 'attack' ? (f === 0 ? 3 : 7) : 0;
  const victory = pose === 'victory';
  const leftArmX = tx - 3;
  const rightArmX = tx + 14;
  const swing = pose === 'walk' ? [0, 1, 0, -1][f] : 0;
  {
    c.rect(leftArmX, ty + 1 + swing, 3, 10, armColor);
    c.rect(leftArmX, ty + 10 + swing, 3, 2, L.skin);
  }
  if (victory) {
    c.rect(rightArmX, ty - 9, 3, 11, armColor);
    c.rect(rightArmX, ty - 11, 3, 2, L.skin);
  } else {
    const rx = rightArmX + (side >= 0 ? attackReach : 0);
    c.rect(rx, ty + 1 - swing - (attackReach ? 3 : 0), 3, 10, armColor);
    c.rect(rx, ty + 10 - swing - (attackReach ? 3 : 0), 3, 2, L.skin);
  }
  // weapon in right hand
  const hx = victory ? rightArmX + 1 : rightArmX + 1 + (side >= 0 ? attackReach : 0);
  const hy = victory ? ty - 12 : ty + 10 - swing - (attackReach ? 3 : 0);
  if (dir !== 'up') {
    if (L.weapon === 'sword') {
      if (attackReach || victory) {
        c.rect(hx, hy - 14, 2, 14, hex('#dfe6f2'));
        c.rect(hx - 2, hy - 1, 6, 2, hex('#8a6a2a'));
      } else {
        c.rect(hx, hy, 2, 12, hex('#dfe6f2'));
        c.rect(hx - 2, hy, 6, 2, hex('#8a6a2a'));
      }
    } else {
      c.rect(hx, hy - 16, 2, 26, hex('#7a5230'));
      c.ellipse(hx + 1, hy - 18, 3, 3, hex('#8fe3ff'));
    }
  }
  // head
  const hcx = cx + lean + side;
  const hcy = top + 9;
  c.ellipse(hcx, hcy, 9, 8.5, L.skin);
  // hair
  if (dir === 'up') {
    c.ellipse(hcx, hcy, 9.5, 9, L.hair);
  } else {
    c.ellipse(hcx, hcy - 4, 9.5, 5.5, L.hair);
    if (side) c.ellipse(hcx - side * 6, hcy, 4, 7, L.hair);
    else {
      c.rect(hcx - 9, hcy - 4, 3, 8, L.hair);
      c.rect(hcx + 7, hcy - 4, 3, 8, L.hair);
    }
    // eyes
    const eye = hex('#2a2238');
    if (pose === 'hurt') {
      c.px(hcx - 4 + side * 2, hcy + 1, eye);
      c.px(hcx - 3 + side * 2, hcy + 2, eye);
      c.px(hcx + 3 + side * 2, hcy + 1, eye);
      c.px(hcx + 4 + side * 2, hcy + 2, eye);
    } else if (side === 0) {
      c.rect(hcx - 4, hcy + 1, 2, 3, eye);
      c.rect(hcx + 3, hcy + 1, 2, 3, eye);
      c.px(hcx - 4, hcy + 1, hex('#ffffff'));
      c.px(hcx + 3, hcy + 1, hex('#ffffff'));
      c.px(hcx - 6, hcy + 5, hex('#f29b9b'));
      c.px(hcx + 6, hcy + 5, hex('#f29b9b'));
    } else {
      c.rect(hcx + side * 4, hcy + 1, 2, 3, eye);
    }
  }
  if (L.hat) {
    c.rect(hcx - 11, hcy - 6, 22, 3, L.tunicDark);
    for (let i = 0; i < 11; i++) c.rect(hcx - 7 + Math.floor(i * 0.6) - side * Math.floor(i / 4), hcy - 7 - i, 14 - Math.floor(i * 1.2), 1, L.tunic);
    c.px(hcx + 1 - side * 3, hcy - 18, L.accent);
  }
  if (dir === 'up' && L.weapon === 'sword') {
    c.line(cx - 6, ty - 2, cx + 6, ty + 14, hex('#dfe6f2'));
  }
}

function buildCharacter(key: string, L: Look) {
  const sheet = new Canvas(48 * FRAMES.length, 64 * DIRS.length);
  DIRS.forEach((dir, row) =>
    FRAMES.forEach(({ pose, f }, col) => {
      const frame = new Canvas(48, 64);
      drawCharacter(frame, 0, 0, dir, pose, f, L);
      if (pose === 'hurt') {
        for (let i = 0; i < frame.data.length; i += 4)
          if (frame.data[i + 3]) frame.data[i] = Math.min(255, frame.data[i] + 70);
      }
      frame.outline(OUTLINE);
      const withShadow = new Canvas(48, 64);
      shadow(withShadow, 24, 60, 10, 3);
      withShadow.blit(frame, 0, 0);
      sheet.blit(withShadow, col * 48, row * 64);
    }),
  );
  sheet.save(`${OUT}/sprites/${key}.png`);
  register({
    key, file: `sprites/${key}.png`, category: 'spritesheet', width: sheet.w, height: sheet.h, frameWidth: 48, frameHeight: 64,
    frames: FRAMES.length * DIRS.length, anchor: { x: 0.5, y: 0.94 },
    notes: 'rows: down,left,right,up · cols: idle×2, walk×4, attack×2, hurt, victory',
  });
}

