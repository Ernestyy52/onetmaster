// Bundles the shared game rules (src/server/gameHandler.ts and everything it imports) into one ESM
// file the Deno Edge Function can import. Run: npm run supabase:build (also part of supabase:deploy).
import { build } from 'esbuild';

await build({
  entryPoints: ['src/server/gameHandler.ts'],
  outfile: 'supabase/functions/game/engine.bundle.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  legalComments: 'none',
  banner: { js: '// GENERATED by tools/supabase/build-functions.ts — do not edit. Source: src/server/gameHandler.ts' },
});
console.log('wrote supabase/functions/game/engine.bundle.js');
