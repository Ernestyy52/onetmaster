// Writes supabase/migrations/0002_seed_questions.sql from src/shared/data/questions.ts.
// Run: npm run supabase:seed   (re-run after editing the question bank; commit the output)
// Items keep their review_status; the game Edge Function only serves 'review' items when the
// ALLOW_REVIEW_QUESTIONS secret is 'true' (dev only).
import { writeFileSync } from 'node:fs';
import { QUESTION_BANK } from '../../src/shared/data/questions';

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = QUESTION_BANK.map(
  (q) => `  (${lit(q.id)}, ${q.version}, ${lit(q.subject)}, ${lit(q.skill_id)}, ${lit(q.review_status)}, ${lit(JSON.stringify(q))}::jsonb)`,
);
const sql = `-- GENERATED by tools/supabase/gen-question-seed.ts — do not edit by hand.
-- ${QUESTION_BANK.length} prototype questions (status as in the repo; not teacher-approved yet).
insert into public.question_versions (id, version, subject, skill_id, review_status, item) values
${rows.join(',\n')}
on conflict (id, version) do nothing;
`;
writeFileSync('supabase/migrations/0002_seed_questions.sql', sql);
console.log(`wrote ${QUESTION_BANK.length} questions`);
